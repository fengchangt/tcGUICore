#!/usr/bin/env bash
# 把 SurgeonConsole 加入 Raspberry Pi labwc / XDG 图形会话开机自启。
# 用法：
#   ./scripts/install_surgeon_console_autostart.sh
#   ./scripts/install_surgeon_console_autostart.sh /path/to/SurgeonConsole
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BIN="${1:-}"
if [[ -z "$BIN" ]]; then
  arch="$(uname -m)"
  case "$arch" in
    aarch64|arm64) PLATFORM="lin-arm64" ;;
    armv7l|armv6l) PLATFORM="lin-arm" ;;
    *) PLATFORM="lin-x64" ;;
  esac
  BIN="$ROOT/bin/${PLATFORM}/release/SurgeonConsole"
fi
if [[ ! -x "$BIN" ]]; then
  echo "找不到可执行文件: $BIN"
  echo "请先编译，或把二进制路径作为参数传入。"
  exit 1
fi

DIR="$(cd "$(dirname "$BIN")" && pwd)"
EXE="$DIR/$(basename "$BIN")"
USER_HOME="${SUDO_USER:+$(getent passwd "$SUDO_USER" | cut -d: -f6)}"
USER_HOME="${USER_HOME:-$HOME}"
if [[ -n "${SUDO_USER:-}" ]]; then
  USER_NAME="$SUDO_USER"
else
  USER_NAME="$(id -un)"
fi

WRAPPER="$DIR/SurgeonConsole-autostart.sh"
cat > "$WRAPPER" <<EOF
#!/usr/bin/env bash
# Generated by install_surgeon_console_autostart.sh — wait for labwc, then start once.
set -u
EXE=$(printf '%q' "$EXE")
DIR=$(printf '%q' "$DIR")
LOG_DIR="\${XDG_STATE_HOME:-\$HOME/.local/state}/surgeon-console"
mkdir -p "\$LOG_DIR"
LOG="\$LOG_DIR/autostart.log"
LOCK="\$DIR/SurgeonConsole.lock"
exec 9>"\$LOCK"
if ! flock -n 9; then
  echo "==== \$(date -Iseconds) pid=\$\$ lock busy, skip ====" >>"\$LOG"
  exit 0
fi

{
  echo "==== \$(date -Iseconds) pid=\$\$ ===="
  echo "user=\$(id -un) DISPLAY=\${DISPLAY-} WAYLAND_DISPLAY=\${WAYLAND_DISPLAY-} XDG_RUNTIME_DIR=\${XDG_RUNTIME_DIR-}"
} >>"\$LOG"

export TCGUICORE_FULLSCREEN="\${TCGUICORE_FULLSCREEN:-1}"
export TCGUICORE_MAXIMIZE="\${TCGUICORE_MAXIMIZE:-1}"
export DISPLAY="\${DISPLAY:-:0}"
RUNTIME="\${XDG_RUNTIME_DIR:-/run/user/\$(id -u)}"

ready=0
for i in \$(seq 1 80); do
  if [[ -n "\${WAYLAND_DISPLAY:-}" && -S "\$RUNTIME/\$WAYLAND_DISPLAY" ]]; then
    ready=1
    echo "wayland ready after \${i} tries (\${WAYLAND_DISPLAY})" >>"\$LOG"
    break
  fi
  sleep 0.25
done
if [[ "\$ready" -eq 0 ]]; then
  echo "warning: compositor not detected, launching anyway" >>"\$LOG"
fi

# Let the panel map, then poke Xwayland so GLFW/GLX has a display.
sleep 3
if command -v xdpyinfo >/dev/null 2>&1; then
  xdpyinfo -display "\$DISPLAY" >/dev/null 2>&1 || true
fi

cd "\$DIR" || exit 1
echo "\$(date -Iseconds) launch \$EXE (once)" >>"\$LOG"
exec "\$EXE" >>"\$LOG" 2>&1
EOF
chmod 755 "$WRAPPER"

# XDG + labwc together launched three copies last time. Keep a disabled
# desktop file for reference and start only from labwc (with flock).
AUTO="$USER_HOME/.config/autostart"
mkdir -p "$AUTO"
DESKTOP="$AUTO/SurgeonConsole.desktop"
cat > "$DESKTOP" <<EOF
[Desktop Entry]
Type=Application
Version=1.0
Name=Surgeon Console
Comment=Lingkui surgeon console
Exec=$WRAPPER
Path=$DIR
Terminal=false
Hidden=true
NoDisplay=true
StartupNotify=false
X-GNOME-Autostart-enabled=false
EOF
chmod 644 "$DESKTOP"

# Raspberry Pi OS (labwc) runs ~/.config/labwc/autostart *instead of*
# /etc/xdg/labwc/autostart when the user file exists. Keep the system
# session pieces and add a delayed launch.
LABWC_DIR="$USER_HOME/.config/labwc"
mkdir -p "$LABWC_DIR"
LABWC_AUTO="$LABWC_DIR/autostart"
if [[ ! -f "$LABWC_AUTO" ]]; then
  if [[ -f /etc/xdg/labwc/autostart ]]; then
    cp /etc/xdg/labwc/autostart "$LABWC_AUTO"
  else
    cat > "$LABWC_AUTO" <<'SYS'
/usr/bin/lwrespawn /usr/bin/pcmanfm-pi &
/usr/bin/lwrespawn /usr/bin/wf-panel-pi &
/usr/bin/kanshi &
/usr/bin/lxsession-xdg-autostart
SYS
  fi
fi
if ! grep -Fq "SurgeonConsole-autostart.sh" "$LABWC_AUTO"; then
  {
    echo ""
    echo "# Surgeon Console kiosk"
    echo "$WRAPPER &"
  } >> "$LABWC_AUTO"
fi
chmod 755 "$LABWC_AUTO"
if [[ "$(id -un)" = "root" && -n "$USER_NAME" ]]; then
  chown "$USER_NAME":"$USER_NAME" "$LABWC_AUTO" "$DESKTOP" "$WRAPPER" 2>/dev/null || true
  chown -R "$USER_NAME":"$USER_NAME" "$LABWC_DIR" "$AUTO" 2>/dev/null || true
fi

echo "已写入 XDG 自启: $DESKTOP"
echo "已写入 labwc 自启: $LABWC_AUTO"
echo "启动包装脚本: $WRAPPER"
echo "日志: $USER_HOME/.local/state/surgeon-console/autostart.log"
echo "下次图形登录会等待桌面就绪后全屏启动 SurgeonConsole。"
echo "取消自启: rm -f \"$DESKTOP\" 并从 $LABWC_AUTO 删除 SurgeonConsole 行"
